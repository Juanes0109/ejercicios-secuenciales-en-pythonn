import math

num = float(input("Ingrese un numero: "))

seno = math.sin(num)
coseno = math.cos(num)
tangente = math.tan(num)
raizz = math.sqrt(num)
logaritmoNatural = math.log(num)
logaritmo10 = math.log10(num)

print("Del numero", num)
print("Su seno es", seno)
print("Su coseno es", coseno)
print("Su tangente es", tangente)
print("Su raiz cuadrada es", raizz)
print("Su logaritmo natural es", logaritmoNatural)
print("Su logaritmo 10 es", logaritmo10)